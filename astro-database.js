function elRel(a, b) { return EL_REL[`${a}|${b}`] || EL_REL[`${b}|${a}`]; }

export function signPairText(s1, s2) {
  const A = getEl(s1), B = getEl(s2);
  const [base, title, desc] = elRel(A.element, B.element);
  let score = base;
  if (A.modality === B.modality) score += A.modality === 'fixed' ? -5 : 3;
  else score += 5;
  if (A.polarity === B.polarity) score += 2; else score += 4;
  if (s1 === s2) score += 2;
  score = Math.max(25, Math.min(99, Math.round(score)));
  const modNote = A.modality === B.modality
    ? `Оба знака принадлежат к ${MODALITIES[A.modality].label.toLowerCase()} кресту: вы двигаетесь на одной скорости, но делите на двоих и общий риск — ${MODALITIES[A.modality].risk}.`
    : `Ваши кресты (${MODALITIES[A.modality].label} и ${MODALITIES[B.modality].label}) образуют комплементарную сцепку: один запускает процесс, другой удерживает или гибко адаптирует его.`;
  return {
    score, title,
    text: [
      `${A.glyph} ${A.label} × ${B.glyph} ${B.label} — «${title}» · Индекс резонанса: ${score}/100.`,
      desc,
      modNote,
      `💎 Золотой фонд союза: объединение «${A.gift}» и «${B.gift}».`,
      `🌑 Точка уязвимости: столкновение «${A.risk}» и «${B.risk}».`,
      `🧭 Формула гармонизации: соедините принцип «${A.key}» (${A.label}) с принципом «${B.key}» (${B.label}).`
    ].join('\n\n')
  };
}

