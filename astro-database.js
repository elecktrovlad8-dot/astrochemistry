export function biorhythms(birth, date = new Date()) {
  const bDate = new Date(birth);
  const days = Math.floor((date - bDate) / 86400000);
  const calc = (dCount, p) => Math.round(Math.sin((2 * Math.PI * dCount) / p) * 100);
  const physical = calc(days, 23);
  const emotional = calc(days, 28);
  const intellectual = calc(days, 33);
  const intuitive = calc(days, 38);
  const average = Math.round((physical + emotional + intellectual + intuitive) / 4);

  const forecast = [];
  for (let i = 0; i < 10; i++) {
    const dt = new Date(date.getTime() + i * 86400000);
    const dStep = days + i;
    const ph = calc(dStep, 23), em = calc(dStep, 28), inl = calc(dStep, 33), intv = calc(dStep, 38);
    const isCritical = Math.abs(ph) <= 13 || Math.abs(em) <= 11 || Math.abs(inl) <= 10;
    forecast.push({
      date: dt,
      physical: ph,
      emotional: em,
      intellectual: inl,
      intuitive: intv,
      isCritical
    });
  }

  return { days, physical, emotional, intellectual, intuitive, average, forecast };
}

