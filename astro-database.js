      const { tp, asp } = bestHit;
      const delta = asp.weight;
      if (['sun', 'mars', 'jupiter'].includes(nat.planetId) || ['sun', 'mars'].includes(tp.planetId)) energy += delta;
      if (['venus', 'moon'].includes(nat.planetId) || ['venus', 'moon'].includes(tp.planetId) || nat.houseId === 'h5' || nat.houseId === 'h7') love += delta;
