/**
 * Автоматическая сборка полной натальной карты (15 связок Планета + Знак + Дом) по дате и времени рождения
 */
export function generateNatalChart(birthDateStr, birthTimeStr = '12:00', maxPlanets = 12) {
  const date = birthDateStr ? new Date(birthDateStr + 'T' + (birthTimeStr || '12:00') + ':00') : new Date();
  const lons = planetLongitudes(date, birthTimeStr);
  const ascSignIdx = Math.floor(norm360(lons.asc) / 30);

  const list = PLANETS.slice(0, maxPlanets).map(P => {
    const lon = lons[P.id] ?? 0;
    const signIdx = Math.floor(norm360(lon) / 30);
    const sign = SIGNS[signIdx];
    const houseIdx = ((signIdx - ascSignIdx) % 12 + 12) % 12;
    const house = HOUSES[houseIdx];
    return {
      planetId: P.id,
      signId: sign.id,
      houseId: house.id,
      degree: Math.round(norm360(lon) % 30),
      isComplete: true,
      text: `${P.glyph} ${sign.glyph} ${house.glyph}`,
      label: `${P.label} · ${sign.prep} · ${house.num} дом`
    };
  });
  return list;
}

