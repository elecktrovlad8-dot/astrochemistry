/**
 * Repository: единая точка доступа к справочнику элементов.
 * Инкапсулирует построение словаря id -> сущность,
 * скрывая деталь реализации (Map) от потребителей (DIP).
 */
export class ElementsRepository {
    #dict;

    constructor() {
        this.#dict = new Map();
        [...BASE_SIGNS, ...BASE_PLANETS, ...BASE_HOUSES].forEach(item => {
            this.#dict.set(item.id, item);
        });
    }

    /** @param {string} id @returns {object|undefined} */
    get(id) {
        return this.#dict.get(id);
    }

    has(id) {
        return this.#dict.has(id);
    }

    getSigns() { return BASE_SIGNS; }
    getPlanets() { return BASE_PLANETS; }
    getHouses() { return BASE_HOUSES; }
}

/**
 * Repository для текстов интерпретаций.
 * Инкапсулирует fallback-логику ("текст не найден") в одном месте
 * вместо разбросанных проверок по коду.
 */
export class DescriptionsRepository {
    #db;

    constructor(db = DESCRIPTIONS_DB) {
        this.#db = db;
    }

    /** @returns {string|null} */
    find(key) {
        return Object.prototype.hasOwnProperty.call(this.#db, key) ? this.#db[key] : null;
    }
}
