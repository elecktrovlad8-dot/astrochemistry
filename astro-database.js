export function dignity(pid, sid) {
  if (!pid || !sid) return null;
  const r = RULER[pid] || [];
  if (r.includes(sid)) return {
    code: 'domicile', label: 'Обитель', score: 2,
    note: 'Планета в собственном замке: качество проявляется автономно, чисто и с максимальным КПД — это ваш природный стержень.'
  };
  if (EXALT[pid] === sid) return {
    code: 'exalt', label: 'Экзальтация', score: 1.5,
    note: 'Планета на пьедестале почётного гостя: талант звучит ярко, вдохновенно и заметно для всех, главное — беречься от перегрева.'
  };
  if (r.some(s => OPP[s] === sid)) return {
    code: 'detriment', label: 'Изгнание', score: -1.5,
    note: 'Планета на чужой территории: стандартные шаблоны здесь не работают, поэтому вы вырабатываете уникальную, нестандартную мастерскую стратегию.'
  };
  if (EXALT[pid] && OPP[EXALT[pid]] === sid) return {
    code: 'fall', label: 'Падение', score: -1,
    note: 'Точка сверхчувствительности и глубинного комплекса: преодолев внутреннее сомнение, вы обретаете здесь самую мощную и выстраданную экспертизу.'
  };
  return null;
}

