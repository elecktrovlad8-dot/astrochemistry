const W = Object.fromEntries(PLANETS.map(p => [p.id, p.w]));

export function chartStats(placements = []) {
  const el = { fire: 0, earth: 0, air: 0, water: 0 };
  const mod = { cardinal: 0, fixed: 0, mutable: 0 };
  const pol = { yang: 0, yin: 0 };
  const quad = { q1: 0, q2: 0, q3: 0, q4: 0 };
  const hemi = { north: 0, south: 0, east: 0, west: 0 };
  const houseFocus = {};
  let total = 0, dignityScore = 0;

  placements.forEach(p => {
    const w = W[p.planetId] ?? 1;
    const S = p.signId && getEl(p.signId);
    if (S) {
      el[S.element] += w;
      mod[S.modality] += w;
      pol[S.polarity] += w;
      total += w;
      if (p.planetId) {
        const d = dignity(p.planetId, p.signId);
        if (d) dignityScore += d.score;
      }
    }
    const H = p.houseId && getEl(p.houseId);
    if (H) {
      const n = H.num;
      houseFocus[H.id] = (houseFocus[H.id] || 0) + w;
      if (n <= 3) quad.q1 += w; else if (n <= 6) quad.q2 += w; else if (n <= 9) quad.q3 += w; else quad.q4 += w;
      if (n <= 6) hemi.north += w; else hemi.south += w;
      if (n <= 3 || n >= 10) hemi.east += w; else hemi.west += w;
    }
  });

  const pct = o => {
    const s = Object.values(o).reduce((a, b) => a + b, 0) || 1;
    return Object.fromEntries(Object.entries(o).map(([k, v]) => [k, total ? Math.round((v / s) * 100) : 0]));
  };
  const eP = pct(el), mP = pct(mod), pP = pct(pol);
  const sortedEl = Object.entries(eP).sort((a, b) => b[1] - a[1]);
  const sortedMod = Object.entries(mP).sort((a, b) => b[1] - a[1]);
  const dominant = total ? sortedEl[0] : null;
  const secondary = total && sortedEl[1] ? sortedEl[1] : null;
  const missing = total ? Object.entries(eP).filter(([, v]) => v <= 8).map(([k]) => k) : [];

  // Индекс гармоничности (энтропия Шеннона по 4 стихиям: 100% = идеальный баланс 25/25/25/25)
  let balanceIndex = 0;
  if (total > 0) {
    const probs = Object.values(el).map(v => v / total).filter(v => v > 0);
    const entropy = -probs.reduce((acc, p) => acc + p * Math.log2(p), 0);
    balanceIndex = Math.round((entropy / 2) * 100);
  }

  // Системная роль человека по доминанте стихии и креста
  let archetypeRole = 'Универсальный Навигатор';
  if (dominant) {
    const roleMap = {
      'fire|cardinal': 'Инициатор-Первопроходец', 'fire|fixed': 'Харизматический Ядерный Центр', 'fire|mutable': 'Идеолог и Вдохновитель',
      'earth|cardinal': 'Стратег и Архитектор Системы', 'earth|fixed': 'Хранитель Капитала и Опоры', 'earth|mutable': 'Мастер Точной Настройки',
      'air|cardinal': 'Дипломат и Модератор Связей', 'air|fixed': 'Визионер и Интеллектуальный Якорь', 'air|mutable': 'Коммуникатор и Сетевой Интегратор',
      'water|cardinal': 'Хранитель Родового Очага', 'water|fixed': 'Глубинный Кризис-Трансформатор', 'water|mutable': 'Эмпат и Духовный Медиатор'
    };
    archetypeRole = roleMap[`${dominant[0]}|${sortedMod[0][0]}`] || archetypeRole;
  }

  return {
    count: placements.length,
    weight: Math.round(total * 10) / 10,
    dignityScore: Math.round(dignityScore * 10) / 10,
    balanceIndex,
    archetypeRole,
    elements: eP,
    modalities: mP,
    polarity: pP,
    quadrants: pct(quad),
    hemispheres: pct(hemi),
    dominantElement: dominant ? dominant[0] : null,
    dominantPct: dominant ? dominant[1] : 0,
    secondaryElement: secondary ? secondary[0] : null,
    dominantModality: total ? sortedMod[0][0] : null,
    missingElements: missing,
    raw: { el, mod, pol, houseFocus }
  };
}

