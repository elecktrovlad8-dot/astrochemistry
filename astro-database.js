export function analyzeTreeSystem(people = [], links = []) {
  const allCharts = people.map(p => p.chart || []);
  const combined = combineStats(allCharts);

  // Анализ каждой линии связи (родовая передача / партнёрская синергия / братский резонанс / дружба)
  const lineAnalyses = links.map(l => {
    const A = people.find(p => p.id === l.a);
    const B = people.find(p => p.id === l.b);
    if (!A || !B) return null;
    const sa = chartStats(A.chart || []);
    const sb = chartStats(B.chart || []);
    const syn = synergyCharts(A.chart || [], B.chart || []);

    const inheritedPlacements = [];
    const crossHouseTriggers = [];
    const elementShift = (sa.dominantElement && sb.dominantElement)
      ? (sa.dominantElement === sb.dominantElement
        ? `Прямая эстафета стихии ${ELEMENTS[sa.dominantElement].label} ${ELEMENTS[sa.dominantElement].icon} (${sa.dominantPct}% → ${sb.dominantPct}%)`
        : `Трансформация стихии: ${ELEMENTS[sa.dominantElement].label} ${ELEMENTS[sa.dominantElement].icon} → ${ELEMENTS[sb.dominantElement].label} ${ELEMENTS[sb.dominantElement].icon}`)
      : 'Ожидание заполнения карт';

    (A.chart || []).forEach(f1 => (B.chart || []).forEach(f2 => {
      if (f1.planetId && f2.planetId && f1.signId && f1.signId === f2.signId) {
        if (f1.planetId === f2.planetId) {
          inheritedPlacements.push(`Прямое повторение: ${getEl(f1.planetId).label} ${getEl(f1.signId).prep}`);
        } else {
          inheritedPlacements.push(`Эстафета знака ${getEl(f1.signId).label}: ${getEl(f1.planetId).label} (${A.name}) → ${getEl(f2.planetId).label} (${B.name})`);
        }
      }
      if (f1.planetId && f2.houseId && f1.houseId === f2.houseId) {
        crossHouseTriggers.push(`Общий ${getEl(f1.houseId).num} дом (${getEl(f1.houseId).focus}): ${getEl(f1.planetId).label} ↔ ${getEl(f2.planetId).label}`);
      }
    }));

    const lineTypeMeta = {
      parent:  { title: 'Родовая линия (Родитель → Ребёнок)', mechanism: 'Вертикальная передача родового кода, талантов и непрожитых сценариев' },
      partner: { title: 'Партнёрский союз', mechanism: 'Горизонтальная алхимия: притяжение по дефицитам и сотворение общего поля' },
      sibling: { title: 'Братско-сестринская ось', mechanism: 'Распределение родовых ролей внутри одного поколения' },
      friend:  { title: 'Духовное и дружеское родство', mechanism: 'Свободный резонанс по ценностям и домам будущего' }
    }[l.type] || { title: 'Линия связи', mechanism: 'Взаимный обмен энергиями' };

    return {
      link: l, A, B, sa, sb, score: syn.score,
      meta: lineTypeMeta,
      elementShift,
      inheritedPlacements: [...new Set(inheritedPlacements)],
      crossHouseTriggers: [...new Set(crossHouseTriggers)],
      notes: syn.notes
    };
  }).filter(Boolean);

  // Распределение ролей в Древе
  const roles = people.map(p => {
    const st = chartStats(p.chart || []);
    return {
      person: p,
      stats: st,
      role: st.archetypeRole,
      coversDeficit: combined.missingElements.length === 0 && st.dominantElement
        ? `Удерживает опору стихии ${ELEMENTS[st.dominantElement].label} ${ELEMENTS[st.dominantElement].icon}`
        : 'Свободный агент системы'
    };
  });

  // Вычисление системной миссии древа
  const domEl = combined.dominantElement ? ELEMENTS[combined.dominantElement] : null;
  const systemMission = domEl
    ? `Коллективный эгрегор вашего Древа базируется на стихии ${domEl.label} ${domEl.icon} (${combined.dominantPct}%). Главный дар вашей системы — ${domEl.gift}. Главный урок рода/круга — преодолеть ${domEl.risk} и интегрировать процесс «${domEl.alchemy}».`
    : 'Добавьте астрологические связки участникам Древа, чтобы рассчитать коллективный эгрегор и родовую миссию.';

  return {
    combined,
    lineAnalyses,
    roles,
    systemMission,
    avgSynergy: lineAnalyses.length
      ? Math.round(lineAnalyses.reduce((a, b) => a + b.score, 0) / lineAnalyses.length)
      : 0
  };
  }
