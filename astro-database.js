/* Seeded PRNG */
export function mulberry32(a) {
  return function () {
    a |= 0; a = a + 0x6D2B79F5 | 0;
    let t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}
export const seedFrom = str => {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
};

/**
 * Мульти-колодный расклад Оракула:
 * - deckIds: массив ID выбранных колод (например ['angels', 'universe', 'shadow'])
 * - mode:
 *    'parallel' — для КАЖДОЙ позиции расклада вытягивается по карте из КАЖДОЙ выбранной колоды!
 *    'mix'      — выбранные колоды смешиваются в единый поток и тянутся по позициям.
 */
export function drawOracleSpread(spreadId, deckIds = ['angels', 'universe'], seedStr = '', mode = 'parallel') {
  const sp = SPREADS.find(s => s.id === spreadId) || SPREADS[0];
  const validDecks = ORACLE_DECKS.filter(d => deckIds.includes(d.id));
  const activeDecks = validDecks.length ? validDecks : [ORACLE_DECKS[0]];
  const rnd = mulberry32(seedFrom(seedStr + '|' + activeDecks.map(d => d.id).join(',') + '|' + mode));

  const cards = [];
  if (mode === 'parallel' && activeDecks.length > 1 && sp.count <= 3) {
    // Для каждого вопроса/позиции тянем сразу из всех выбранных колод
    sp.positions.forEach(pos => {
      activeDecks.forEach(deck => {
        const pool = ORACLE_CARDS.filter(c => c.deckId === deck.id);
        const idx = Math.floor(rnd() * pool.length);
        const card = pool[idx];
        cards.push({
          position: `${pos} · ${deck.icon} ${deck.short}`,
          basePosition: pos,
          deck,
          card,
          reversed: false
        });
      });
    });
  } else {
    // Смешанный пул из всех выбранных колод (или одной колоды)
    const pool = ORACLE_CARDS.filter(c => activeDecks.some(d => d.id === c.deckId));
    const workingPool = [...pool];
    for (let i = 0; i < sp.count; i++) {
      if (!workingPool.length) workingPool.push(...pool);
      const idx = Math.floor(rnd() * workingPool.length);
      const card = workingPool.splice(idx, 1)[0];
      const deck = ORACLE_DECKS.find(d => d.id === card.deckId) || activeDecks[0];
      cards.push({
        position: activeDecks.length > 1 ? `${sp.positions[i]} · ${deck.icon} ${deck.short}` : sp.positions[i],
        basePosition: sp.positions[i],
        deck,
        card,
        reversed: false
      });
    }
  }

  return { spread: sp, activeDecks, mode, cards };
}

export function drawSpread(spreadId, seedStr, deckIds = ['angels', 'universe'], mode = 'mix') {
  return drawOracleSpread(spreadId, deckIds, seedStr, mode);
}

/* ============================================================================
 *  11. ТОЧНЫЕ ЭФЕМЕРИДЫ ВСЕХ ПЛАНЕТ, АВТО-НАТАЛ И ПЕРСОНАЛЬНЫЕ ТРАНЗИТЫ
 * ========================================================================= */
const RAD = Math.PI / 180;
const norm360 = x => ((x % 360) + 360) % 360;
const daysSinceJ2000 = d => (d.getTime() / 86400000) - 10957.5;

export function sunLongitude(date) {
  const n = daysSinceJ2000(date);
  const L = norm360(280.460 + 0.9856474 * n);
  const g = norm360(357.528 + 0.9856003 * n);
  return norm360(L + 1.915 * Math.sin(g * RAD) + 0.020 * Math.sin(2 * g * RAD));
}

export function moonLongitude(date) {
  const n = daysSinceJ2000(date);
  const L = norm360(218.316 + 13.176396 * n);
  const M = norm360(134.963 + 13.064993 * n);
  const D = norm360(297.850 + 12.190749 * n);
  return norm360(L + 6.289 * Math.sin(M * RAD) + 1.274 * Math.sin((2 * D - M) * RAD) + 0.658 * Math.sin(2 * D * RAD));
}

/**
 * Расчёт эклиптических долгот всех 15 астрологических точек на любую дату
 */
export function planetLongitudes(date = new Date(), birthTimeStr = '12:00') {
  const d = daysSinceJ2000(date);
  const sun = sunLongitude(date);
  const moon = moonLongitude(date);

  // Гелиоцентрические/геоцентрические орбитальные гармоники для планет
  const mercury = norm360(sun + 18 * Math.sin((252.25 + 4.09233 * d) * RAD) + 4 * Math.cos((180 + 4.09233 * d) * RAD));
  const venus   = norm360(sun + 42 * Math.sin((181.98 + 1.60213 * d) * RAD) + 3 * Math.sin((300 + 3.204 * d) * RAD));
  const mars    = norm360(355.43 + 0.524033 * d + 10.69 * Math.sin((19.37 + 0.52402 * d) * RAD));
  const jupiter = norm360(34.35 + 0.083085 * d + 5.55 * Math.sin((20.02 + 0.08308 * d) * RAD));
  const saturn  = norm360(50.08 + 0.033460 * d + 6.40 * Math.sin((317.02 + 0.03346 * d) * RAD));
  const uranus  = norm360(314.05 + 0.011731 * d + 2.70 * Math.sin((142.59 + 0.01173 * d) * RAD));
  const neptune = norm360(304.35 + 0.005981 * d + 1.00 * Math.sin((256.22 + 0.00598 * d) * RAD));
  const pluto   = norm360(238.93 + 0.003968 * d + 14.0 * Math.sin((14.86 + 0.00397 * d) * RAD));
  const node_n  = norm360(125.04 - 0.0529539 * d);
  const node_s  = norm360(node_n + 180);
  const lilith  = norm360(83.35 + 0.111404 * d);
  const chiron  = norm360(209.35 + 0.0196 * d + 6.0 * Math.sin((110 + 0.0196 * d) * RAD));

  // Асцендент с учётом времени суток (по умолчанию в полдень Солнце в 10 доме, ASC в +90° от Солнца)
  let hours = 12;
  if (birthTimeStr && typeof birthTimeStr === 'string' && birthTimeStr.includes(':')) {
    const [hh, mm] = birthTimeStr.split(':').map(Number);
    if (!Number.isNaN(hh)) hours = hh + (mm || 0) / 60;
  }
  const asc = norm360(sun + (hours - 6) * 15);

  return { sun, moon, mercury, venus, mars, jupiter, saturn, uranus, neptune, pluto, node_n, node_s, lilith, chiron, asc };
}

